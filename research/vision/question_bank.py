"""Typed question templates for Laya-V teacher labelling.

Six image domains x 30 templates. Each template is a Laya question (`type`, `instructions`,
`criteria`) with a stable id; `build_question_bank.py` adds two English paraphrases and
translations, and `sample_questions` draws 10 per image.

Conventions, from the README's known quirks:
- `choice` keys are semantic snake_case words; every choice set has an escape option
  (`other`, `none`, `not_applicable`, ...) so the teacher is never forced into a wrong key.
- `noul` questions are phrased positively (no negations) and use the default labels.
- `score` levels run from least to most, 4 levels each.
"""
from typing import Dict, List

DOMAINS = ("photo", "document", "receipt", "chart", "screenshot", "meme")


def N(qid, ins):
    return {"id": qid, "type": "noul", "instructions": ins}


def C(qid, ins, crit):
    return {"id": qid, "type": "choice", "instructions": ins, "criteria": crit}


def S(qid, ins, levels):
    return {"id": qid, "type": "score", "instructions": ins, "criteria": list(levels)}


