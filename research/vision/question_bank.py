def option_keys(q: Dict) -> List[str]:
    """Option names the teacher must return probabilities for, in Laya's label order."""
    if q["type"] == "choice":
        return list(q["criteria"].keys())
    if q["type"] == "score":
        return [str(i) for i in range(len(q["criteria"]))]
    return ["false", "true"]
